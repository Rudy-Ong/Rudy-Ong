/**
 * Precomputes SVG outlines for every kana used by the shiritori snake.
 *
 * Why this exists: GitHub renders README images through a proxy and does not
 * load webfonts, so a <text> element containing kana falls back to whatever the
 * viewer happens to have — usually tofu boxes. Converting the glyphs to <path>
 * outlines makes the SVG self-contained and identical everywhere.
 *
 * This runs rarely (only when the word pool gains a new character), and its
 * output — data/kana-paths.json — is committed. The daily build therefore needs
 * no font and no opentype.js at all.
 *
 *   npm run build:kana
 *   npm run build:kana -- --font path/to/Font.ttf
 *
 * Font: M PLUS 1p Bold (SIL Open Font License 1.1). A bold static face is used
 * because the glyphs render near contribution-cell size, where lighter weights
 * disappear. Outlines from an OFL font may be redistributed; see assets/OFL.txt.
 */

import { readFile, writeFile, mkdir, stat } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CACHE = join(ROOT, '.cache');
const FONT_URL = 'https://github.com/google/fonts/raw/main/ofl/mplus1p/MPLUS1p-Bold.ttf';
const FONT_NAME = 'M PLUS 1p Bold';
const FONT_LICENSE = 'SIL Open Font License 1.1';

/** Outlines are extracted on a 1000-unit em so the renderer can scale cleanly. */
const EM = 1000;

async function exists(path) {
  try {
    await stat(path);
    return true;
  } catch {
    return false;
  }
}

async function resolveFont() {
  const flagIndex = process.argv.indexOf('--font');
  if (flagIndex !== -1 && process.argv[flagIndex + 1]) {
    return process.argv[flagIndex + 1];
  }

  await mkdir(CACHE, { recursive: true });
  const cached = join(CACHE, 'MPLUS1p-Bold.ttf');
  if (await exists(cached)) {
    console.log('[kana] using cached font');
    return cached;
  }

  console.log('[kana] downloading M PLUS 1p Bold…');
  const res = await fetch(FONT_URL);
  if (!res.ok) throw new Error(`Font download failed: ${res.status} ${res.statusText}`);
  const buf = Buffer.from(await res.arrayBuffer());
  await writeFile(cached, buf);
  console.log(`[kana] cached ${(buf.length / 1024 / 1024).toFixed(1)} MB`);
  return cached;
}

/** Every distinct character the word pool can put on screen. */
function collectChars(pool) {
  const set = new Set();
  for (const word of pool) for (const ch of word.kana) set.add(ch);
  return [...set].sort();
}

async function main() {
  const poolPath = join(ROOT, 'data', 'shiritori-words.json');
  const { words } = JSON.parse(await readFile(poolPath, 'utf8'));
  const chars = collectChars(words);

  const fontPath = await resolveFont();
  const buf = await readFile(fontPath);
  // opentype.parse wants a plain ArrayBuffer; a Node Buffer is a view into a
  // possibly larger pool, so slice to exactly this file's bytes.
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

  const glyphs = {};
  const missing = [];

  for (const ch of chars) {
    const glyph = font.charToGlyph(ch);
    // opentype returns .notdef (index 0) for characters the font lacks.
    if (!glyph || glyph.index === 0) {
      missing.push(ch);
      continue;
    }

    // Baseline at y=0, y increasing downward — SVG's convention.
    const path = glyph.getPath(0, 0, EM);
    const d = path.toPathData(2);
    const bbox = path.getBoundingBox();

    glyphs[ch] = {
      d,
      advance: Number(((glyph.advanceWidth / font.unitsPerEm) * EM).toFixed(2)),
      bbox: {
        x1: Number(bbox.x1.toFixed(2)),
        y1: Number(bbox.y1.toFixed(2)),
        x2: Number(bbox.x2.toFixed(2)),
        y2: Number(bbox.y2.toFixed(2)),
      },
    };
  }

  if (missing.length) {
    throw new Error(`Font is missing glyphs for: ${missing.join(' ')}`);
  }

  const output = {
    _comment:
      'GENERATED by scripts/build-kana-paths.mjs — do not edit by hand. Outlines from M PLUS 1p Bold (SIL OFL 1.1), extracted on a 1000-unit em with the baseline at y=0.',
    font: FONT_NAME,
    license: FONT_LICENSE,
    em: EM,
    glyphs,
  };

  const outPath = join(ROOT, 'data', 'kana-paths.json');
  const json = `${JSON.stringify(output, null, 1)}\n`;
  await writeFile(outPath, json, 'utf8');

  console.log(
    `[kana] wrote data/kana-paths.json — ${chars.length} glyphs, ${(json.length / 1024).toFixed(1)} KB`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
